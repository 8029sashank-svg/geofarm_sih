const LanguageContext = createContext(undefined);

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    try {
      const stored = window.localStorage.getItem(STORAGE_KEY);
      if (stored && TRANSLATIONS[stored]) return stored;
    } catch (err) {
      // localStorage unavailable — fall back silently
    }
    return 'en';
  });

  const setLanguage = useCallback((lang) => {
    if (!TRANSLATIONS[lang]) return;
    setLanguageState(lang);
    try {
      window.localStorage.setItem(STORAGE_KEY, lang);
    } catch (err) {
      // ignore persistence failures
    }
  }, []);

  // 3-way cycle: en → mr → hi → en (the UI also exposes setLanguage directly)
  const toggleLanguage = useCallback(() => {
    const idx = CYCLE.indexOf(language);
    const next = idx === -1 ? 'mr' : CYCLE[(idx + 1) % CYCLE.length];
    setLanguage(next);
  }, [language, setLanguage]);

  const t = useCallback(
    (key) => {
      const dict = TRANSLATIONS[language] || TRANSLATIONS.en;
      return dict[key] ?? TRANSLATIONS.en[key] ?? key;
    },
    [language]
  );

  // Label for the next language in the cycle (shown on the button)
  const nextLanguageLabel = useMemo(() => {
    const idx = CYCLE.indexOf(language);
    const next = idx === -1 ? 'mr' : CYCLE[(idx + 1) % CYCLE.length];
    return LANGUAGES[next]?.nativeLabel || 'मराठी';
  }, [language]);

  const value = useMemo(
    () => ({
      language,
      setLanguage,
      toggleLanguage,
      t,
      isMarathi: language === 'mr',
      isHindi: language === 'hi',
      isDevanagari: language === 'mr' || language === 'hi',
      nextLanguageLabel,
      availableLanguages: LANGUAGES,
    }),
    [language, setLanguage, toggleLanguage, t, nextLanguageLabel]
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return ctx;
}

export default LanguageContext;
